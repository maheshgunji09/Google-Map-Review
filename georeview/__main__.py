"""Command line entry point for both the demonstration and authorized research runs."""

import argparse
import hashlib
import json
import platform
import sys
import tempfile
from datetime import datetime, timezone
from importlib.metadata import version
from pathlib import Path
from uuid import uuid4

from .demo import write_demo


def existing_file(value):
    path = Path(value)
    if not path.is_file():
        raise argparse.ArgumentTypeError(f"File does not exist: {path}")
    return path


def dataset_fingerprint(path):
    with path.open("rb") as stream:
        return {"filename": path.name, "sha256": hashlib.file_digest(stream, "sha256").hexdigest()}


def destination(requested, kind):
    if requested is None:
        requested = Path("outputs") / kind
        if requested.exists():
            date = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
            requested = requested.with_name(f"{kind}-{date}-{uuid4().hex[:6]}")
    if requested.exists():
        raise ValueError(f"Output already exists: {requested}. Choose a new --output directory.")
    return requested.resolve()


def execute(args):
    from .ingest import prepare
    from .model import run_model
    from .report import write_report

    demo = args.command == "demo"
    kind = "synthetic" if demo else "research"
    prepared_only = getattr(args, "prepare_only", False)
    if not demo and not args.reuse_note.strip():
        raise ValueError("Provide the applicable research-use basis in --reuse-note.")
    if min(args.k_values) < 2 or args.max_fit < 4 or not 0 <= args.seed < 2**32:
        raise ValueError("Use k >= 2, a fit cap >= 4 and a seed between 0 and 4294967295.")
    default_name = "demo" if demo else "research-prepared" if prepared_only else "research"
    out = destination(args.output, default_name)
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".georeview-", dir=out.parent) as work:
        work_dir = Path(work)
        stage = work_dir / "result"
        stage.mkdir()
        if demo:
            places, reviews = write_demo(work_dir, args.seed)
        else:
            places, reviews = args.places, args.reviews
        manifest = {
            "schema_version": 1, "dataset_kind": kind,
            "source_title": "Fictional Indian businesses" if demo else "UCSD Google Local Reviews (2018)",
            "source_identification": "generated by this project" if demo else "declared by the operator",
            "provenance_note": ("Seeded fictional places and review events for testing the analysis."
                                if demo else args.reuse_note.strip()),
            "source_files": {"places": dataset_fingerprint(places), "reviews": dataset_fingerprint(reviews)},
            "seed": args.seed, "requested_k": args.k_values, "max_fit": args.max_fit,
            "sentiment_requested": args.sentiment, "stage": "prepared" if prepared_only else "complete",
            "python": platform.python_version(),
            "packages": {name: version(name) for name in
                         ["numpy", "pandas", "scipy", "scikit-learn", "threadpoolctl"]},
        }
        print("Validating locations and aggregating eligible reviews...", flush=True)
        prepare(places, reviews, stage, sentiment=args.sentiment)
        if not prepared_only:
            print("Comparing clustering configurations and measuring stability...", flush=True)
            run_model(stage / "businesses.csv", stage, k_values=args.k_values,
                      random_seed=args.seed, max_fit=args.max_fit)
            write_report(stage, manifest)
        (stage / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        # Publish only complete outputs. A failed run leaves previous results usable.
        stage.rename(out)
    print(f"Saved {kind} {'prepared data' if prepared_only else 'analysis'} to {out}")
    if not prepared_only:
        print(f"Dashboard run directory (GEOREVIEW_RUN): {out}")
    return out


def main():
    parser = argparse.ArgumentParser(description="GeoReview India business segmentation")
    commands = parser.add_subparsers(dest="command", required=True)
    demo = commands.add_parser("demo", help="Run the full workflow on a seeded fictional dataset")
    research = commands.add_parser("research", help="Analyze authorized local 2018 archive files")
    research.add_argument("--places", required=True, type=existing_file)
    research.add_argument("--reviews", required=True, type=existing_file)
    research.add_argument("--reuse-note", required=True,
                          help="Record the applicable permission or terms reference for this use")
    research.add_argument("--prepare-only", action="store_true",
                          help="Save validated reviews, business features and the exclusion audit")
    for command in (demo, research):
        command.add_argument("--output", type=Path, help="A new run directory (default: under outputs/)")
        command.add_argument("--seed", type=int, default=42)
        command.add_argument("--k", dest="k_values", type=int, nargs="+", default=[2, 3, 4, 5, 6])
        command.add_argument("--max-fit", type=int, default=2000,
                             help="Maximum businesses to fit in the common comparison cohort")
        command.add_argument("--sentiment", action="store_true", help="Enable conservative text scoring")
    args = parser.parse_args()
    try:
        execute(args)
    except (ValueError, OSError) as error:
        print(f"GeoReview: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
